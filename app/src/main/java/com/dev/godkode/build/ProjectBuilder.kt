package com.dev.godkode.build

import android.content.Context
import com.blankj.utilcode.util.ToastUtils
import com.dev.godkode.extensions.createFileIfNot
import java.io.File

/**
 * In-app Gradle build wrapper.
 *
 * GodKode does NOT ship an Android toolchain (the official NDK/SDK are x86_64-host
 * binaries and won't run natively on arm64). Instead the user configures a path to
 * an existing toolchain (Termux / AndroidIDE / manual) via Settings.Builder, and
 * this class turns an "open project" + "Build APK" action into a single command run
 * inside the existing proot jail terminal:
 *
 *   ./gradlew <task> <args>      with JAVA_HOME / ANDROID_HOME / NDK_HOME wired in
 *
 * Output streams to the terminal session — no separate build UI.
 */
object ProjectBuilder {

    /**
     * Walk up from [from] until a Gradle project root is found
     * (a directory containing a `settings.gradle(.kts)` or `gradlew`).
     * Returns null if none on the way up to / .
     */
    fun findGradleRoot(from: File): File? {
        var dir: File? = from.absoluteFile.let { if (it.isFile) it.parentFile ?: it else it }
        while (dir != null) {
            val settings = File(dir, "settings.gradle")
            val settingsKts = File(dir, "settings.gradle.kts")
            val gradlew = File(dir, "gradlew")
            if ((settings.exists() || settingsKts.exists()) && gradlew.exists()) {
                return dir
            }
            dir = dir.parentFile
        }
        return null
    }

    /** Toolchain config resolved from Settings (or nulls when unset). */
    data class Toolchain(
        val javaHome: String,
        val androidHome: String,
        val ndkHome: String,
    ) {
        fun isComplete(): Boolean =
            javaHome.isNotBlank() && androidHome.isNotBlank()
    }

    /**
     * Write `local.properties` (sdk.dir/ndk.dir) and a low-memory
     * `gradle.properties` into [projectRoot]. Idempotent; overwrites.
     */
    fun prepareProject(projectRoot: File, tc: Toolchain) {
        // local.properties — Gradle reads sdk.dir / ndk.dir from here.
        val localProps = File(projectRoot, "local.properties").apply { createFileIfNot() }
        localProps.writeText(
            buildString {
                append("## Auto-generated by GodKode Builder\n")
                if (tc.androidHome.isNotBlank()) append("sdk.dir=").append(tc.androidHome).append('\n')
                if (tc.ndkHome.isNotBlank()) append("ndk.dir=").append(tc.ndkHome).append('\n')
            }
        )

        // gradle.properties — keep memory/scheduling sane on a phone.
        // We only add a couple of low-mem flags; merge-friendly (overwrites our own keys).
        val gradleProps = File(projectRoot, "gradle.properties").apply { createFileIfNot() }
        val ours = setOf(
            "org.gradle.jvmargs",
            "org.gradle.parallel",
            "org.gradle.workers.max",
            "org.gradle.caching",
            "org.gradle.configureondemand",
            "android.builder.sdkDownload",
            "android.suppressUnsupportedCompileSdk",
        )
        val keep = gradleProps.readLines()
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .filterNot { line -> ours.any { key -> line.trimStart().startsWith(key) } }
            .joinToString("\n")
        gradleProps.writeText(
            buildString {
                append(keep)
                if (keep.isNotBlank() && !keep.endsWith('\n')) append('\n')
                append("## GodKode low-memory build tuning\n")
                append("org.gradle.jvmargs=-Xmx1024M -XX:MaxMetaspaceSize=512M -Dfile.encoding=UTF-8\n")
                append("org.gradle.parallel=false\n")
                append("org.gradle.workers.max=1\n")
                append("org.gradle.caching=true\n")
                append("org.gradle.configureondemand=false\n")
                append("android.builder.sdkDownload=false\n")
            }
        )
    }

    /**
     * The full command to run inside the jail: cd into project, export env,
     * chmod gradlew, run the task.
     */
    fun buildCommand(
        projectRoot: File,
        tc: Toolchain,
        task: String,
        gradleArgs: String,
    ): String {
        val sb = StringBuilder()
        sb.append("cd ").append(shellQuote(projectRoot.absolutePath)).append(" && ")
        if (tc.javaHome.isNotBlank()) {
            sb.append("export JAVA_HOME=").append(shellQuote(tc.javaHome)).append(" && ")
            sb.append("export PATH=\"\$JAVA_HOME/bin:\$PATH\" && ")
        }
        if (tc.androidHome.isNotBlank()) {
            sb.append("export ANDROID_HOME=").append(shellQuote(tc.androidHome))
                .append(" && export ANDROID_SDK_ROOT=\$ANDROID_HOME && ")
        }
        if (tc.ndkHome.isNotBlank()) {
            sb.append("export ANDROID_NDK_HOME=").append(shellQuote(tc.ndkHome))
                .append(" && export ANDROID_NDK_ROOT=\$ANDROID_NDK_HOME && ")
        }
        sb.append("chmod +x ./gradlew 2>/dev/null; ")
        sb.append("./gradlew ").append(task)
        if (gradleArgs.isNotBlank()) sb.append(' ').append(gradleArgs)
        return sb.toString()
    }

    /** Quick sanity check with a toast if the toolchain isn't configured. */
    fun requireToolchainOrToast(context: Context, tc: Toolchain): Boolean {
        if (tc.isComplete()) return true
        ToastUtils.showLong(
            "Toolchain not configured. Set JAVA_HOME and Android SDK in Settings → Builder."
        )
        return false
    }

    private fun shellQuote(s: String): String =
        "'" + s.replace("'", "'\"'\"'") + "'"
}
